# ── Video Inspection ───────────────────────────────────────────────────────

class VideoInfo(BaseModel):
    """Result of FFprobe inspection on an input video."""
    path: str
    filename: str
    duration: float
    width: int
    height: int
    fps: float
    codec: str
    has_audio: bool
    audio_codec: Optional[str] = None
    file_size_mb: float
